export type Locale = keyof typeof translations;
export type TranslationKey = keyof typeof translations.pt;

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("pt");

  useEffect(() => {
    const saved = window.localStorage.getItem("sc2rw-locale");
    const browserLocale: Locale = navigator.language.toLowerCase().startsWith("pt") ? "pt" : "en";
    const timer = window.setTimeout(() => {
      setLocaleState(saved === "pt" || saved === "en" ? saved : browserLocale);
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "pt" ? "pt-BR" : "en";
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: (nextLocale) => {
      window.localStorage.setItem("sc2rw-locale", nextLocale);
      setLocaleState(nextLocale);
    },
    t: (key, params) => Object.entries(params ?? {}).reduce(
      (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
      translations[locale][key] as string,
    ),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
